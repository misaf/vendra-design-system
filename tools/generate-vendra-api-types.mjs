import {readFileSync} from 'node:fs';

const [file, revision] = process.argv.slice(2);
if (!file || !/^[a-f0-9]{40}$/.test(revision ?? '')) {
  throw new Error('Usage: node tools/generate-vendra-api-types.mjs OPENAPI_JSON LARAVEL_COMMIT');
}

const {components} = JSON.parse(readFileSync(file, 'utf8'));

// Keep this projection to the fields the florist purchase adapters consume.
const resources = {
  CheckoutInput: ['Checkout', ['cartToken']],
  QuoteInput: ['DeliveryQuote', ['latitude', 'longitude']],
  ProductResource: ['Product.jsonld', ['id', 'token', 'name', 'slug', 'inStock']],
  CartResource: ['Cart.jsonld', ['id', 'token', 'expiresAt', 'lines']],
  CartLineResource: ['CartLine.jsonld'],
  ScheduleResource: ['DeliverySchedule.jsonld', ['dates', 'slots']],
  SlotResource: ['DeliverySlot.jsonld'],
  OrderResource: [
    'Order.jsonld',
    [
      'id',
      'number',
      'status',
      'currencyCode',
      'itemsAmount',
      'deliveryAmount',
      'totalAmount',
      'placedAt',
      'lines'
    ]
  ],
  OrderLineResource: ['OrderLine.jsonld']
};

const references = new Map(Object.entries(resources).map(([name, [key]]) => [key, name]));
const primitives = {
  string: 'string',
  number: 'number',
  integer: 'number',
  boolean: 'boolean',
  null: 'null'
};

function typeOf(schema) {
  if (schema.$ref) {
    const type = references.get(schema.$ref.replace('#/components/schemas/', ''));
    if (type) return type;
  }
  if (Array.isArray(schema.type)) {
    return schema.type.map(type => typeOf({...schema, type})).join(' | ');
  }
  if (schema.type === 'array') return `Array<${typeOf(schema.items)}>`;
  if (schema.type === 'object' && schema.additionalProperties) {
    return `Record<string, ${typeOf(schema.additionalProperties)}>`;
  }
  if (Object.hasOwn(primitives, schema.type)) return primitives[schema.type];
  throw new Error(`Unsupported OpenAPI schema: ${JSON.stringify(schema)}`);
}

const declarations = Object.entries(resources).map(([name, [key, fields]]) => {
  const schema = components.schemas[key];
  const properties = schema.properties ?? schema.allOf.find(part => part.properties).properties;
  // API Platform omits request required lists for Laravel validation rules. For responses,
  // Laravel's JSON-LD serializer omits nulls, while these non-null projections are present.
  const keys = name.endsWith('Input')
    ? Object.keys(properties)
    : (fields ?? Object.keys(properties));
  const lines = keys.map(field => {
    const shape = properties[field];
    if (!shape) throw new Error(`Missing ${key}.${field}`);
    const type = typeOf(shape);
    const optional = name.endsWith('Input') ? !fields.includes(field) : type.endsWith(' | null');
    return `  ${field}${optional ? '?' : ''}: ${type};`;
  });
  return `export interface ${name} {\n${lines.join('\n')}\n}`;
});

process.stdout.write(
  `// Generated by tools/generate-vendra-api-types.mjs from misaf/vendra@${revision}.\n\n` +
    declarations.join('\n\n') +
    '\n'
);
